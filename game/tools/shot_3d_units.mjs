import { chromium } from "playwright-core";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto("http://localhost:4182/", { waitUntil: "networkidle" });
await page.waitForFunction(() => (window).__units, null, { timeout: 120000 });
const units = await page.evaluate(() => (window).__units);
console.log("UNITS:", JSON.stringify(units));
await page.evaluate(() => document.getElementById("tiltView").click());
await page.waitForTimeout(4000);
await page.screenshot({ path: "../docs/3d-units-tilt.png" });
await page.evaluate(() => document.getElementById("eastView").click());
await page.waitForTimeout(4000);
await page.screenshot({ path: "../docs/3d-units-east.png" });
await page.mouse.move(770, 400);
await page.mouse.wheel(0, -1400);
await page.waitForTimeout(3500);
await page.screenshot({ path: "../docs/3d-units-nanjing.png" });
const labelCount = await page.evaluate(() => document.querySelectorAll(".unit-label").length);
console.log("labels:", labelCount);
await browser.close();
console.log("SHOTS DONE");
